def slot_reuse():
    """Needle-style retrieval on llama.cpp (benchmark/slot_reuse.py, 2026-08-29).

    Three graders, so one friendly needle cannot carry it: an exact 8-character
    code at depth; a CONTRADICTION (two conflicting values, the LATER one is
    correct); and a DATE among plausible distractors. Each cell is probed twice,
    before and after a different large request has occupied and released the
    server slot, because the failure being hunted was a silent wrong answer
    after slot reuse rather than an inability to retrieve at all."""
    out = []
    for fn, label, ctx, slots in SLOT_RUNS:
        f = R / "results" / "slot_reuse" / fn
        if not f.is_file(): continue
        j = json.loads(f.read_text())
        rows = j.get("rows", [])
        out.append(dict(label=label, ctx=ctx, slots=slots, n=j.get("n", len(rows)),
                        fresh=j.get("fresh", 0), reused=j.get("reused", 0),
                        tasks=sorted({r["task"] for r in rows}),
                        depths=sorted({r["depth"] for r in rows}), artifact=fn))
    return out

TIER_ORDER = ["nogpu", "8", "16", "24", "32", "48", "96"]
TIER_NCMOE = {"nogpu": 48, "8": 48, "16": 45, "24": 42, "32": 36, "48": 23, "96": 0}

def tier_mtp():
    """MTP against a VRAM budget (results/tier_mtp/, 2026-09-07).

    A smaller card is simulated by holding VRAM with benchmark/vram_cap.py, and
    each tier keeps the expert offload the published ladder used, so the arms sit
    at the old placements. What varies is only the draft head: off, or on the GPU.

    Reads verdicts.json (written by bench/tier_classify.py) so an arm that did
    not complete is carried as its verdict rather than silently missing."""
    f = R / "results" / "tier_mtp" / "verdicts.json"
    if not f.is_file(): return []
    try: rows = json.loads(f.read_text())
    except Exception: return []
    best = {}
    for r in rows:
        # smoke arms were the same config as the ladder proper; keep the ladder's.
        if str(r.get("label", "")).startswith("smoke"): continue
        dec = None
        d = (r.get("decode") or "").split()
        if d:
            try: dec = float(d[0])
            except ValueError: dec = None
        best[(r["tier"], r["spec"])] = dict(
            tier=r["tier"], spec=r["spec"], decode=dec, verdict=r.get("verdict", "?"),
            n_cpu_moe=TIER_NCMOE.get(r["tier"]), artifact=r.get("artifact"))
    out = []
    for t in TIER_ORDER:
        row = {"tier": t, "n_cpu_moe": TIER_NCMOE.get(t)}
        for spec in ("off", "gpu", "cpu"):
            a = best.get((t, spec))
            if a: row[spec] = a
        if len(row) > 2: out.append(row)
    return out

def resident_newbuild():
    """The PR #28136 build at the RESIDENT headline config (load-mode none,
    LAZY=off) against the b10666 control at the same ISL and ubatch. The lazy
    arms showed the newer build decoding faster under mmap; this isolates the
    build from the placement."""
    # Speculation OFF only. An MTP arm here would report the draft head and the
    # build as one number; the draft head is section 10's subject, not this one's.
    def _plain(pf, wp, j):
        return (str(pf.get("ubatch")) == "1024" and pf.get("load_mode") == "none"
                and str(wp.get("isl")) in ("8192", "32000")
                and str(pf.get("spec_type") or "none") in ("none", "unset"))
    ctrl = {str(a["isl_label"]): a for a in _code_arms(lambda pf, wp, j:
            pf.get("image_tag") in (None, "default") and _plain(pf, wp, j))}
    out = []
    # every non-default llama.cpp tag that ran the resident config (PR build, b10819, ...)
    tags = sorted({a["tag"] for a in _code_arms(lambda pf, wp, j:
                   pf.get("image_tag") not in (None, "default") and _plain(pf, wp, j))})
    for tag in tags:
        new = {str(a["isl_label"]): a for a in _code_arms(
               lambda pf, wp, j, t=tag: pf.get("image_tag") == t and _plain(pf, wp, j))}
        for isl in ("8192", "32000"):
            if isl in ctrl and isl in new:
                c, n_ = ctrl[isl], new[isl]
                out.append(dict(isl=isl, tag=tag, ctrl=c, new=n_,
                                prefill_x=(n_["prefill"] / c["prefill"]) if c["prefill"] and n_["prefill"] else None,
                                decode_x=(n_["decode"] / c["decode"]) if c["decode"] and n_["decode"] else None))
    return out


