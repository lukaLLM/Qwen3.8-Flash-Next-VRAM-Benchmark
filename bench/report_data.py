def boot_times():
    """Time from a cold container to a SERVED ANSWER, N times per engine.

    Three clocks exist and only the third is comparable:

      health_ok_s  the /health endpoint returning 200, polled every 0.25 s.
        Looks like the neutral choice and is NOT: FreeToken answers /health at
        3.3 s and cannot serve anything for another 78 s. A 200 means the HTTP
        server is up, which is not the same claim on every engine.
      boot_s       what `docker compose up -d --wait` waits for -- each image's
        own healthcheck. FreeToken's asserts maintenance=='serving' and is
        therefore meaningful; llama.cpp's and SGLang's only curl /health, and
        the 15 s poll interval quantises them (llama.cpp reported 15.8 s on
        every attempt while genuinely up at 10.7-15.5 s).
      to_first_answer_s = boot_s + first_gen_s. What a person actually waits:
        start the container, wait until it serves, get an answer back. Same
        question for every engine, no engine-specific definition of 'ready'.
        This is the headline; the parts are kept so the shape is visible."""
    out = {}
    for e in ENGINES:
        for d in sorted(A.glob(f"boot_{e}_*"), key=lambda x: x.stat().st_mtime, reverse=True):
            f = d / "boots.json"
            if not f.is_file(): continue
            try: rows = json.loads(f.read_text())
            except Exception: continue
            if not rows: continue
            med = lambda v: sorted(v)[len(v)//2] if v else None
            boot = [r["boot_s"] for r in rows]
            gen = [r["first_gen_s"] for r in rows if r.get("gen_ok")]
            total = [r["boot_s"] + r["first_gen_s"] for r in rows if r.get("gen_ok")]
            hok = [r["health_ok_s"] for r in rows if "health_ok_s" in r]
            out[LABEL[e]] = dict(n=len(rows), artifact=d.name,
                                 total=total, total_med=med(total), total_first=(total[0] if total else None),
                                 total_best=(min(total) if total else None),
                                 boot_med=med(boot), gen_med=med(gen),
                                 http_med=med(hok) if hok else None)
            break
    return out

def ft_cache():
    """FreeToken's live pool resize. Sizes come from the NEWEST sweep only: an
    earlier sweep sent the identical prompt twice and was answered from the
    prefix cache (53.3 s then 4.5 s at one size), so merging the two would put
    cache-served times in the same column as real ones. Rebuild COSTS are pooled
    across every sweep, because that measurement is unaffected."""
    dirs = sorted(A.glob("ftcache_*"), key=lambda x: x.stat().st_mtime)
    dirs = [d for d in dirs if (d / "sweep.json").is_file()]
    if not dirs: return dict(sizes=[], geometry=None, rebuilds=[])
    rebuilds = []
    for d in dirs:
        for r in json.loads((d / "sweep.json").read_text()):
            if r.get("rebuild_status") == "ok": rebuilds.append(float(r["rebuild_s"]))
    latest = dirs[-1]
    reps = {}
    rf = latest / "reps.txt"
    if rf.is_file():
        for line in rf.read_text().splitlines():
            parts = line.split()
            if len(parts) >= 5:
                kv, rep, el, comp, prompt = parts[:5]
                reps.setdefault(int(kv), []).append(dict(rep=int(rep), s=float(el),
                                                         out_tokens=int(comp), in_tokens=int(prompt)))
    sizes = []
    for r in json.loads((latest / "sweep.json").read_text()):
        kv = r["kv_tokens_requested"]
        rs = reps.get(kv, [])
        # Attempt 1 at the first size pays the engine's own first-request warmup
        # (43.6 s measured separately), so the STEADY time is the later rep.
        sizes.append(dict(r, reps=rs, steady=(rs[-1]["s"] if rs else None),
                          in_tokens=(rs[0]["in_tokens"] if rs else None), artifact=latest.name))
    geo = None
    g = latest / "geometry_boot.json"
    if g.is_file():
        try: geo = json.loads(g.read_text()).get("geometry")
        except Exception: pass
    return dict(sizes=sorted(sizes, key=lambda r: -r["kv_tokens_requested"]),
                geometry=geo, rebuilds=rebuilds, artifact=latest.name)

