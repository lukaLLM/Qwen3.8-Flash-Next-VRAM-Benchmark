def energy_per_request():
    """Joules for ONE full-window request: median power under load multiplied by
    the time that request occupies the card (time to first token plus its 128
    decoded tokens at the measured rate). Approximate by construction - it uses
    a median power over the arm rather than integrating one request - and it is
    reported as a ratio, which is where it is robust."""
    fc, th = full_context(), thermals()
    out = {}
    for key, r in fc.items():
        lab = LABEL[key]
        t = th.get(lab)
        if not t or not r["ttft"] or not r["decode"]: continue
        secs = r["ttft"] / 1000 + (r["osl"] or 128) / r["decode"]
        out[lab] = dict(seconds=secs, watts=t["power_med"], kj=t["power_med"] * secs / 1000)
    return out

